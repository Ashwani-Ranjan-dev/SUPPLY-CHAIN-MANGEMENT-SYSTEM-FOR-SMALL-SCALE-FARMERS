
import mongoose from "mongoose";
import PDFDocument from "pdfkit";

import Deal from "../models/DealSchema.js";
import Payment from "../models/PaymentSchema.js";
import PooledDeal from "../models/PooledDealSchema.js";
import PooledPayment from "../models/PooledPaymentSchema.js";

const idOf = (value) => {
    if (!value) return "";
    return String(value._id || value);
};

const formatDate = (value) => {
    if (!value) return "Not recorded";

    const date = new Date(value);

    return Number.isNaN(date.getTime())
        ? "Not recorded"
        : date.toLocaleDateString("en-IN", {
              day: "2-digit",
              month: "short",
              year: "numeric",
          });
};

const money = (value) =>
    `INR ${Number(value || 0).toLocaleString("en-IN", {
        minimumFractionDigits: 2,
        maximumFractionDigits: 2,
    })}`;

const sendPdf = (res, filename, buildPdf) => {
    res.setHeader("Content-Type", "application/pdf");
    res.setHeader(
        "Content-Disposition",
        `attachment; filename="${filename}"`
    );
    res.setHeader("Cache-Control", "private, no-store");

    const pdf = new PDFDocument({
        size: "A4",
        margins: {
            top: 50,
            bottom: 50,
            left: 50,
            right: 50,
        },
        info: {
            Title: filename,
            Author: "KrishiConnect",
        },
    });

    pdf.pipe(res);
    buildPdf(pdf);
    pdf.end();
};

const heading = (pdf, title, subtitle) => {
    pdf.fontSize(22)
        .fillColor("#166534")
        .text("KRISHICONNECT");

    pdf.moveDown(0.4);

    pdf.fontSize(17)
        .fillColor("#111827")
        .text(title);

    pdf.moveDown(0.2);

    pdf.fontSize(9)
        .fillColor("#6B7280")
        .text(subtitle);

    pdf.moveDown(1);
    pdf.moveTo(50, pdf.y)
        .lineTo(545, pdf.y)
        .strokeColor("#D1D5DB")
        .stroke();

    pdf.moveDown(1);
    pdf.fillColor("#111827");
};

const section = (pdf, title) => {
    pdf.moveDown(0.6);
    pdf.fontSize(12)
        .fillColor("#166534")
        .text(title);

    pdf.moveDown(0.3);
    pdf.fontSize(10)
        .fillColor("#111827");
};

const field = (pdf, label, value) => {
    pdf.font("Helvetica-Bold").text(`${label}: `, {
        continued: true,
    });

    pdf.font("Helvetica").text(
        String(value ?? "Not provided")
    );
};

const documentFooter = (pdf) => {
    pdf.moveDown(1.5);

    pdf.fontSize(8)
        .fillColor("#6B7280")
        .text(
            "Generated by KrishiConnect from the recorded platform data. " +
            "Please review the details carefully. This document is a " +
            "project-generated record and is not a substitute for legal advice.",
            {
                align: "left",
            }
        );
};

const userCanAccessDeal = (deal, userId) =>
    idOf(deal.buyer) === userId ||
    idOf(deal.farmer) === userId;

const userCanAccessPooledDeal = (deal, userId) =>
    idOf(deal.buyer) === userId ||
    (deal.contributions || []).some(
        (item) => idOf(item.farmer) === userId
    );

const isDocumentEligible = (status) =>
    ["ACCEPTED", "COMPLETED"].includes(status);

const invalidId = (id) =>
    !mongoose.isValidObjectId(id);

const notFound = (res, message) =>
    res.status(404).json({
        success: false,
        message,
    });

const forbidden = (res) =>
    res.status(403).json({
        success: false,
        message: "You are not authorized to access this document.",
    });

// ======================================================
// REGULAR DEAL CONTRACT
// GET /api/documents/deals/:dealId/contract
// ======================================================

export const downloadDealContract = async (req, res) => {
    try {
        const { dealId } = req.params;

        if (invalidId(dealId)) {
            return res.status(400).json({
                success: false,
                message: "Invalid deal ID.",
            });
        }

        const deal = await Deal.findById(dealId)
            .populate("buyer", "name village")
            .populate("farmer", "name village")
            .populate("produce", "crop unit location quality");

        if (!deal) {
            return notFound(res, "Deal not found.");
        }

        if (!userCanAccessDeal(deal, idOf(req.user._id))) {
            return forbidden(res);
        }

        if (!isDocumentEligible(deal.status)) {
            return res.status(409).json({
                success: false,
                message:
                    "A contract is available only after the deal is accepted.",
            });
        }

        const contractNumber =
            `KC-AGR-${idOf(deal).slice(-8).toUpperCase()}`;

        return sendPdf(
            res,
            `${contractNumber}.pdf`,
            (pdf) => {
                heading(
                    pdf,
                    "Digital Deal Agreement",
                    `Agreement reference: ${contractNumber}`
                );

                field(pdf, "Agreement date", formatDate(deal.updatedAt));
                field(pdf, "Deal status", deal.status);

                section(pdf, "Parties");

                field(pdf, "Buyer", deal.buyer?.name);
                field(pdf, "Buyer village", deal.buyer?.village);
                field(pdf, "Farmer", deal.farmer?.name);
                field(pdf, "Farmer village", deal.farmer?.village);

                section(pdf, "Produce and agreed terms");

                field(
                    pdf,
                    "Produce",
                    deal.produce?.crop || "Produce"
                );
                field(pdf, "Quantity", `${deal.quantity} ${deal.unit}`);
                field(pdf, "Price per unit", money(deal.offeredPrice));
                field(pdf, "Total deal amount", money(deal.totalAmount));
                field(
                    pdf,
                    "Produce location",
                    deal.produce?.location || "Not provided"
                );
                field(pdf, "Deal message", deal.message || "None");

                section(pdf, "Basic agreement terms");

                pdf.text(
                    "1. The farmer agrees to supply the produce and quantity " +
                    "recorded in this agreement, subject to the parties' " +
                    "confirmed arrangements."
                );

                pdf.moveDown(0.4);

                pdf.text(
                    "2. The buyer agrees to pay the recorded total amount " +
                    "through the payment process available on KrishiConnect."
                );

                pdf.moveDown(0.4);

                pdf.text(
                    "3. The parties should separately confirm delivery timing, " +
                    "quality inspection, transport, and any additional terms " +
                    "that are not recorded in this document."
                );

                pdf.moveDown(0.4);

                pdf.text(
                    "4. Any change to the agreed quantity, price, or other " +
                    "terms should be agreed by both parties."
                );

                section(pdf, "Acknowledgement");

                pdf.text(
                    "This document records the deal details stored on " +
                    "KrishiConnect. It does not represent a digital signature " +
                    "or independently confirm either party's identity."
                );

                documentFooter(pdf);
            }
        );
    } catch (error) {
        console.error("Download deal contract error:", error);

        if (!res.headersSent) {
            return res.status(500).json({
                success: false,
                message: "Unable to generate deal contract.",
            });
        }

        res.destroy(error);
    }
};

