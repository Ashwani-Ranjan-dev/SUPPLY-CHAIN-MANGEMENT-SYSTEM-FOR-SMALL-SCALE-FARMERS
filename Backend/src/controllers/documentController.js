// REGULAR DEAL INVOICE
// GET /api/documents/deals/:dealId/invoice
// ======================================================

export const downloadDealInvoice = async (req, res) => {
    try {
        const { dealId } = req.params;

        if (invalidId(dealId)) {
            return res.status(400).json({
                success: false,
                message: "Invalid deal ID.",
            });
        }

        const deal = await Deal.findById(dealId)
            .populate("buyer", "name village")
            .populate("farmer", "name village")
            .populate("produce", "crop unit");

        if (!deal) {
            return notFound(res, "Deal not found.");
        }

        if (!userCanAccessDeal(deal, idOf(req.user._id))) {
            return forbidden(res);
        }

        if (!isDocumentEligible(deal.status)) {
            return res.status(409).json({
                success: false,
                message:
                    "An invoice is available only after the deal is accepted.",
            });
        }

        const payment = await Payment.findOne({
            deal: deal._id,
            buyer: deal.buyer._id,
            farmer: deal.farmer._id,
        }).lean();

        const invoiceNumber =
            `KC-INV-${idOf(deal).slice(-8).toUpperCase()}`;

        return sendPdf(
            res,
            `${invoiceNumber}.pdf`,
            (pdf) => {
                heading(
                    pdf,
                    "Deal Invoice",
                    `Invoice reference: ${invoiceNumber}`
                );

                field(pdf, "Invoice date", formatDate(new Date()));
                field(pdf, "Deal reference", idOf(deal));
                field(pdf, "Deal status", deal.status);

                section(pdf, "Buyer and farmer");

                field(pdf, "Buyer", deal.buyer?.name);
                field(pdf, "Farmer", deal.farmer?.name);

                section(pdf, "Invoice details");

                field(pdf, "Produce", deal.produce?.crop || "Produce");
                field(pdf, "Quantity", `${deal.quantity} ${deal.unit}`);
                field(pdf, "Rate per unit", money(deal.offeredPrice));
                field(pdf, "Total amount", money(deal.totalAmount));

                section(pdf, "Payment details");

                field(
                    pdf,
                    "Payment status",
                    payment?.status || "NOT CREATED"
                );
                field(
                    pdf,
                    "Payment method",
                    payment?.method || "Not recorded"
                );
                field(
                    pdf,
                    "Transaction reference",
                    payment?.transactionId || "Not available"
                );
                field(
                    pdf,
                    "Paid date",
                    payment?.status === "PAID"
                        ? formatDate(payment.paidAt)
                        : "Not paid / not recorded"
                );

                pdf.moveDown(0.5);

                pdf.font("Helvetica-Bold")
                    .text(
                        payment?.status === "PAID"
                            ? "Payment recorded as PAID"
                            : "PAYMENT DUE / NOT CONFIRMED"
                    );

                pdf.font("Helvetica");

                documentFooter(pdf);
            }
        );
    } catch (error) {
        console.error("Download deal invoice error:", error);

        if (!res.headersSent) {
            return res.status(500).json({
                success: false,
                message: "Unable to generate deal invoice.",
            });
        }

        res.destroy(error);
    }
};

// ======================================================
// POOLED DEAL CONTRACT
// GET /api/documents/pooled-deals/:pooledDealId/contract
// ======================================================

export const downloadPooledDealContract = async (req, res) => {
    try {
        const { pooledDealId } = req.params;

        if (invalidId(pooledDealId)) {
            return res.status(400).json({
                success: false,
                message: "Invalid pooled deal ID.",
            });
        }

        const deal = await PooledDeal.findById(pooledDealId)
            .populate("buyer", "name village")
            .populate("pooledLot", "crop unit location quality")
            .populate("contributions.farmer", "name village")
            .populate("contributions.produce", "crop unit");

        if (!deal) {
            return notFound(res, "Pooled deal not found.");
        }

        if (!userCanAccessPooledDeal(deal, idOf(req.user._id))) {
            return forbidden(res);
        }

        if (!isDocumentEligible(deal.status)) {
            return res.status(409).json({
                success: false,
                message:
                    "A pooled contract is available only after the deal is accepted.",
            });
        }

        const contractNumber =
            `KC-PC-${idOf(deal).slice(-8).toUpperCase()}`;

        return sendPdf(
            res,
            `${contractNumber}.pdf`,
            (pdf) => {
                heading(
                    pdf,
                    "Pooled Produce Agreement",
                    `Agreement reference: ${contractNumber}`
                );

                field(pdf, "Agreement date", formatDate(deal.updatedAt));
                field(pdf, "Buyer", deal.buyer?.name);
                field(pdf, "Buyer village", deal.buyer?.village);
                field(pdf, "Deal status", deal.status);

                section(pdf, "Pooled lot details");

                field(
                    pdf,
                    "Produce",
                    deal.pooledLot?.crop || "Pooled produce"
                );
                field(pdf, "Total quantity", `${deal.quantity} ${deal.unit}`);
                field(pdf, "Price per unit", money(deal.offeredPrice));
                field(pdf, "Total deal amount", money(deal.totalAmount));
                field(
                    pdf,
                    "Location",
                    deal.pooledLot?.location || "Not provided"
                );

                section(pdf, "Farmer contributions");

                for (const item of deal.contributions || []) {
                    const farmerName =
                        item.farmer?.name || "Participating farmer";

                    const crop =
                        item.produce?.crop ||
                        deal.pooledLot?.crop ||
                        "Produce";

                    pdf.font("Helvetica-Bold")
                        .text(farmerName);

                    pdf.font("Helvetica");

                    field(pdf, "Produce", crop);
                    field(
                        pdf,
                        "Contribution quantity",
                        `${item.quantity} ${deal.unit}`
                    );
                    field(
                        pdf,
                        "Contribution amount",
                        money(item.offeredAmount)
                    );
                    field(
                        pdf,
                        "Farmer response",
                        item.responseStatus || "PENDING"
                    );

                    pdf.moveDown(0.4);

                    if (pdf.y > 690) {
                        pdf.addPage();
                    }
                }

                section(pdf, "Basic agreement terms");

                pdf.text(
                    "The buyer's offer is based on the total quantity, " +
                    "price, and farmer contributions recorded above. " +
                    "Each contributing farmer is responsible for the " +
                    "contribution associated with that farmer."
                );

                pdf.moveDown(0.4);

                pdf.text(
                    "The parties should confirm delivery arrangements, " +
                    "quality requirements, payment allocation, and any " +
                    "additional terms before proceeding."
                );

                pdf.moveDown(0.4);

                pdf.text(
                    "This document records the platform's deal data. " +
                    "It is not a digital signature and is not a substitute " +
                    "for a separately reviewed legal agreement."
                );

                documentFooter(pdf);
            }
        );
    } catch (error) {
        console.error("Download pooled contract error:", error);

        if (!res.headersSent) {
            return res.status(500).json({
                success: false,
                message: "Unable to generate pooled deal contract.",
            });
        }

        res.destroy(error);
    }
};

